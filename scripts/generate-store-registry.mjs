#!/usr/bin/env node
/**
 * Generates lib/store-registry.generated.ts from the monorepo's
 * stores/<slug>/store.json files — the build-time hostname → store
 * mapping the multi-tenant middleware and the /s/[store] routes read.
 *
 * Wired into the app's dev/build scripts (and predev/prebuild for npm),
 * mirroring how lib/theme-data.generated.ts is produced by `pnpm sync`.
 * The output is committed so a fresh checkout typechecks without a
 * generation step.
 *
 * A store is included when its store.json has all three of:
 *   - siteUrl          (its host is the public hostname to match)
 *   - storeDomain      (the myshopify.com domain)
 *   - storefrontToken  (public Storefront API token — public by design)
 * Incomplete stores are skipped with a warning.
 *
 * A store with `redirectHosts` is NOT served here — it lives standalone
 * at siteUrl, and each listed legacy hostname 308-redirects there
 * (REDIRECT_HOSTS, read by the middleware before store matching).
 *
 * Standalone apps (`zalify theme create` scaffolds) have no stores/
 * directory: the script then writes an empty registry, which disables
 * multi-tenancy entirely — the app keeps its single-store env config.
 */
import {existsSync, readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const storesDir = resolve(appRoot, '../../stores');
const outFile = join(appRoot, 'lib/store-registry.generated.ts');

const entries = [];
const redirects = {};

if (existsSync(storesDir)) {
  for (const dir of readdirSync(storesDir, {withFileTypes: true})) {
    if (!dir.isDirectory()) continue;
    const configPath = join(storesDir, dir.name, 'store.json');
    if (!existsSync(configPath)) continue;
    let store;
    try {
      store = JSON.parse(readFileSync(configPath, 'utf8'));
    } catch (error) {
      console.warn(`[store-registry] skipping ${dir.name}: invalid JSON (${error.message})`);
      continue;
    }
    if (Array.isArray(store.redirectHosts) && store.redirectHosts.length) {
      // Served standalone at siteUrl; legacy hosts redirect there.
      if (store.siteUrl) {
        for (const legacyHost of store.redirectHosts) {
          redirects[String(legacyHost).toLowerCase()] = store.siteUrl;
        }
      } else {
        console.warn(
          `[store-registry] ${dir.name}: redirectHosts without siteUrl — skipped`,
        );
      }
      continue;
    }
    const missing = ['siteUrl', 'storeDomain', 'storefrontToken'].filter(
      (key) => !store[key],
    );
    if (missing.length) {
      console.warn(
        `[store-registry] skipping ${dir.name}: missing ${missing.join(', ')}`,
      );
      continue;
    }
    let host;
    try {
      host = new URL(store.siteUrl).host.toLowerCase();
    } catch {
      console.warn(`[store-registry] skipping ${dir.name}: bad siteUrl "${store.siteUrl}"`);
      continue;
    }
    entries.push({
      slug: store.slug ?? dir.name,
      name: store.name ?? dir.name,
      host,
      storeDomain: store.storeDomain,
      storefrontToken: store.storefrontToken,
    });
  }
}

entries.sort((a, b) => a.slug.localeCompare(b.slug));

const banner = `/* Auto-generated by scripts/generate-store-registry.mjs — do not edit.
 * Regenerated on every dev/build from stores/<slug>/store.json.
 * Empty when the repo has no stores/ registry (standalone scaffolds):
 * the middleware then never rewrites and the app stays single-tenant. */
`;

const body = `${banner}
export interface StoreRegistryEntry {
  slug: string;
  name: string;
  /** Public hostname (from store.json siteUrl) matched against Host. */
  host: string;
  storeDomain: string;
  /** Public Storefront API token — public by design. */
  storefrontToken: string;
}

export const STORE_REGISTRY: StoreRegistryEntry[] = ${JSON.stringify(entries, null, 2)};

/** Legacy hostname → canonical site URL (store.json redirectHosts).
 * The middleware 308-redirects these before store matching. */
export const REDIRECT_HOSTS: Record<string, string> = ${JSON.stringify(redirects, null, 2)};
`;

const previous = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null;
if (previous !== body) {
  writeFileSync(outFile, body);
  console.log(
    `[store-registry] wrote ${entries.length} store(s), ${Object.keys(redirects).length} redirect host(s) to lib/store-registry.generated.ts`,
  );
}
