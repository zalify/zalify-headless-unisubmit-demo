#!/usr/bin/env node
/**
 * Generates lib/store-theme/ from the monorepo's optional
 * stores/<slug>/theme/ folders — the store-owned theme data of the
 * multi-tenant deployment — plus, for standalone scaffolds, an
 * app-local theme/ folder emitted as the 'default' entry (sibling of
 * generate-store-registry.mjs, wired into the same dev/build scripts;
 * output is committed so a fresh checkout typechecks without a
 * generation step).
 *
 * Ownership split:
 *   - THEME owns config/settings_schema.json, section schemas, and the
 *     default settings_data/templates/locales (lib/theme-data.generated.ts,
 *     produced by `pnpm sync`) — the fallback for stores without
 *     overrides and for single-tenant/scaffold apps.
 *   - STORE optionally owns stores/<slug>/theme/:
 *       settings_data.json      replaces the theme default wholesale
 *       templates/*.json        replace the same-named default template
 *       templates/customers/*   same, for customer templates
 *       sections/*-group.json   replace the same-named section group
 *       locales/*.json          OVERRIDES deep-merged over theme defaults
 *
 * Emits one module per store (lib/store-theme/<slug>.generated.ts) plus
 * an index barrel that statically imports them keyed by slug, so the
 * bundler sees plain static imports. Stores without a theme/ folder are
 * simply absent from the map — lib/store-theme-data.ts resolves them to
 * the theme defaults. Standalone scaffolds (no stores/ dir) get an
 * empty map: single-tenant behavior is unchanged.
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const storesDir = resolve(appRoot, '../../stores');
const outDir = join(appRoot, 'lib/store-theme');

/** Parse theme JSON that may carry Shopify's leading block comment. */
function parseThemeJson(raw, name) {
  const stripped = raw.replace(/^\s*\/\*[\s\S]*?\*\//, '').trim();
  try {
    return JSON.parse(stripped);
  } catch (error) {
    throw new Error(`[store-theme] ${name}: invalid JSON — ${error.message}`);
  }
}

function readJsonDir(dir) {
  if (!existsSync(dir)) return null;
  const map = {};
  for (const entry of readdirSync(dir, {withFileTypes: true}).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    if (!entry.isFile() || !entry.name.endsWith('.json')) continue;
    map[entry.name.replace(/\.json$/, '')] = parseThemeJson(
      readFileSync(join(dir, entry.name), 'utf8'),
      join(dir, entry.name),
    );
  }
  return Object.keys(map).length ? map : null;
}

/** Read a theme/ folder into an overrides object; null when empty/absent. */
function readThemeOverrides(themeDir) {
  if (!existsSync(themeDir)) return null;
  const overrides = {};
  const settingsPath = join(themeDir, 'settings_data.json');
  if (existsSync(settingsPath)) {
    overrides.settingsData = parseThemeJson(
      readFileSync(settingsPath, 'utf8'),
      settingsPath,
    );
  }
  const templates = readJsonDir(join(themeDir, 'templates'));
  if (templates) overrides.templates = templates;
  const customerTemplates = readJsonDir(join(themeDir, 'templates/customers'));
  if (customerTemplates) overrides.customerTemplates = customerTemplates;
  const sectionGroups = readJsonDir(join(themeDir, 'sections'));
  if (sectionGroups) overrides.sectionGroups = sectionGroups;
  const locales = readJsonDir(join(themeDir, 'locales'));
  if (locales) overrides.locales = locales;
  return Object.keys(overrides).length ? overrides : null;
}

const stores = [];

if (existsSync(storesDir)) {
  for (const dir of readdirSync(storesDir, {withFileTypes: true}).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    if (!dir.isDirectory()) continue;
    const themeDir = join(storesDir, dir.name, 'theme');
    if (!existsSync(themeDir)) continue;
    const overrides = readThemeOverrides(themeDir);
    if (!overrides) {
      console.warn(`[store-theme] ${dir.name}/theme/ exists but is empty — skipped`);
      continue;
    }
    stores.push({slug: dir.name, overrides, source: `stores/${dir.name}/theme/`});
  }
}

// Standalone scaffolds: a project-local theme/ folder is the store's own
// theme data, resolved as the 'default' slug (what the env-configured
// single-tenant path renders). In the monorepo a stores/default/ would
// shadow it — none exists, and local theme/ wins if one ever does.
const localOverrides = readThemeOverrides(join(appRoot, 'theme'));
if (localOverrides) {
  const existing = stores.findIndex((s) => s.slug === 'default');
  if (existing !== -1) stores.splice(existing, 1);
  stores.push({slug: 'default', overrides: localOverrides, source: 'theme/'});
  stores.sort((a, b) => a.slug.localeCompare(b.slug));
}

const banner = (what) =>
  `/* Auto-generated by scripts/generate-store-theme-data.mjs — do not edit.\n` +
  ` * ${what}\n` +
  ` * Regenerated on every dev/build from stores/<slug>/theme/. */\n`;

mkdirSync(outDir, {recursive: true});

const expected = new Map(); // filename -> content

for (const {slug, overrides, source} of stores) {
  expected.set(
    `${slug}.generated.ts`,
    banner(`Theme-data overrides owned by ${source}.`) +
      `import type {StoreThemeOverrides} from '../store-theme-data';\n\n` +
      `export const overrides: StoreThemeOverrides = ${JSON.stringify(overrides, null, 2)};\n`,
  );
}

const imports = stores
  .map(
    ({slug}, i) => `import {overrides as store${i}} from './${slug}.generated';`,
  )
  .join('\n');
const entries = stores
  .map(({slug}, i) => `  '${slug}': store${i},`)
  .join('\n');
expected.set(
  'index.generated.ts',
  banner(
    'Static slug-keyed map of every store that ships theme overrides.\n' +
      ' * Empty for standalone scaffolds (no stores/ dir) — the resolver\n' +
      ' * then always serves the theme defaults (single-tenant behavior).',
  ) +
    `import type {StoreThemeOverrides} from '../store-theme-data';\n` +
    (imports ? `${imports}\n` : '') +
    `\nexport const STORE_THEME_OVERRIDES: Record<string, StoreThemeOverrides> = {\n${entries}\n};\n`.replace(
      '{\n\n}',
      '{}',
    ),
);

let wrote = 0;
for (const [name, content] of expected) {
  const path = join(outDir, name);
  const previous = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (previous !== content) {
    writeFileSync(path, content);
    wrote++;
  }
}
// Drop modules for stores whose theme/ folder was removed.
for (const onDisk of readdirSync(outDir)) {
  if (onDisk.endsWith('.generated.ts') && !expected.has(onDisk)) {
    rmSync(join(outDir, onDisk));
    console.log(`[store-theme] removed orphaned lib/store-theme/${onDisk}`);
  }
}
if (wrote) {
  console.log(
    `[store-theme] wrote ${stores.length} store override module(s) to lib/store-theme/`,
  );
}
